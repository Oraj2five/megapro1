-- 1. Ensure required cryptographic extension for UUID generation
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. Create sales_forecasts table
CREATE TABLE IF NOT EXISTS public.sales_forecasts (
    -- Unique identifier for the forecast run
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Owner identification: Verified Firebase Authentication UID
    user_id TEXT NOT NULL,

    -- Forecast horizon: strictly constrained to 30, 180, or 365 days
    forecast_days INT NOT NULL,
    CONSTRAINT chk_sales_forecast_horizon CHECK (forecast_days IN (30, 180, 365)),

    -- Historical sales date range and baseline metrics
    historical_start_date DATE,
    historical_end_date DATE,
    historical_total_sales NUMERIC(15, 2) NOT NULL,
    historical_average_daily_sales NUMERIC(15, 2) NOT NULL,
    CONSTRAINT chk_historical_date_order CHECK (
        historical_start_date IS NULL 
        OR historical_end_date IS NULL 
        OR historical_start_date <= historical_end_date
    ),
    CONSTRAINT chk_historical_metrics_non_negative CHECK (
        historical_total_sales >= 0 
        AND historical_average_daily_sales >= 0
    ),

    -- Forecast projection date range and summary KPIs
    forecast_start_date DATE NOT NULL,
    forecast_end_date DATE NOT NULL,
    forecast_total NUMERIC(15, 2) NOT NULL,
    forecast_average NUMERIC(15, 2) NOT NULL,
    expected_growth_percentage NUMERIC(6, 2) NOT NULL,
    CONSTRAINT chk_forecast_date_order CHECK (forecast_start_date <= forecast_end_date),
    CONSTRAINT chk_forecast_metrics_non_negative CHECK (
        forecast_total >= 0 
        AND forecast_average >= 0
    ),

    -- Provenance: Supabase storage path or source CSV URL used for model training
    csv_source_url TEXT NOT NULL,

    -- Detailed daily timeseries predictions array:
    -- Schema per element: { "date": "YYYY-MM-DD", "predicted_sales": 0.00, "lower_bound": 0.00, "upper_bound": 0.00 }
    forecast_records JSONB NOT NULL,

    -- Complete summary payload dictionary preserving all calculated metrics
    summary_metrics JSONB NOT NULL,

    -- Idempotency key to prevent duplicate runs on identical inputs / network retries
    -- Format: deterministic hash or unique client request key (e.g. SHA256 of user_id + csv_source_url + forecast_days + forecast_start_date)
    idempotency_key TEXT,

    -- Audit timestamp (server clock)
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

-- 3. Idempotency Constraint
-- Ensures duplicate network retries or rapid double-submissions with the same idempotency key are rejected
CREATE UNIQUE INDEX IF NOT EXISTS uq_sales_forecasts_idempotency_key
ON public.sales_forecasts (idempotency_key)
WHERE idempotency_key IS NOT NULL;

-- 4. Performance Indexes
-- Composite index for fast user history lookup and latest-forecast queries:
-- SELECT * FROM public.sales_forecasts WHERE user_id = $1 ORDER BY created_at DESC LIMIT 1;
CREATE INDEX IF NOT EXISTS idx_sales_forecasts_user_history
ON public.sales_forecasts (user_id, created_at DESC);

-- Composite index for querying specific forecast horizon runs for a user:
CREATE INDEX IF NOT EXISTS idx_sales_forecasts_user_horizon
ON public.sales_forecasts (user_id, forecast_days, created_at DESC);

-- 5. Row Level Security (RLS) Configuration
-- RLS is ENABLED to lock down direct access.
-- No policies are granted to 'anon' or 'authenticated' roles.
-- All access is mediated strictly through the FastAPI backend using the Supabase service-role key.
ALTER TABLE public.sales_forecasts ENABLE ROW LEVEL SECURITY;

